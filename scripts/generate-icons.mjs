/**
 * Generates the icon set from SVG files: src/images/icons/<name>.svg →
 * - src/box/constants/icons.ts       — ICON_NAMES (camelCase key → file name)
 * - src/components/ui/Icon/icons.tsx — ICONS (viewBox + JSX body for the <Icon> component)
 *
 * Runs before develop / start / build (`npm run icons`). New icon = drop an .svg into the folder and restart.
 * SVG rules: kebab-case file name, root <svg> with viewBox, main color `currentColor` (fill / stroke),
 * secondary colors as they are. ids are prefixed with the icon name, so several icons on a page don't clash.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const ICONS_DIR = path.join(ROOT, "src/images/icons");
const NAMES_FILE = path.join(ROOT, "src/box/constants/icons.ts");
const ICONS_FILE = path.join(ROOT, "src/components/ui/Icon/icons.tsx");

const ICON_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const BODY_INDENT = " ".repeat(8);

/** "arrow-up-right" → "arrowUpRight" */
const toCamelCase = (name) => name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

/** SVG attributes → JSX: kebab-case → camelCase (aria-* / data-* stay), xlink:href → href, class → className */
const toJsxAttributes = (markup) =>
  markup
    .replace(/ xlink:href=/g, " href=")
    .replace(/ class=/g, " className=")
    .replace(/ ((?!aria-|data-)[a-z]+(?:-[a-z]+)+)=/g, (_, attribute) => ` ${toCamelCase(attribute)}=`);

/** Prefixes ids with the icon name and updates the references to them (url(#id), href="#id") */
const prefixIds = (markup, name) => {
  const ids = [...markup.matchAll(/ id="([^"]+)"/g)].map(([, id]) => id);

  return ids.reduce(
    (result, id) =>
      result
        .replaceAll(` id="${id}"`, ` id="icon-${name}-${id}"`)
        .replaceAll(`url(#${id})`, `url(#icon-${name}-${id})`)
        .replaceAll(`href="#${id}"`, `href="#icon-${name}-${id}"`),
    markup,
  );
};

/** Inner markup lines re-indented under `<>` keeping their nesting */
const formatBody = (markup) => {
  const lines = markup.split("\n").filter((line) => line.trim());
  const minIndent = Math.min(...lines.map((line) => line.match(/^ */)[0].length));

  return lines.map((line) => BODY_INDENT + line.slice(minIndent).trimEnd().replace(/"\/>/g, '" />')).join("\n");
};

const parseIcon = (fileName) => {
  const name = path.basename(fileName, ".svg");

  if (!ICON_NAME.test(name)) {
    throw new Error(`Icon file "${fileName}": use a kebab-case name, e.g. "arrow-left.svg"`);
  }

  const source = fs
    .readFileSync(path.join(ICONS_DIR, fileName), "utf8")
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "");
  const [, rootAttributes = "", inner = ""] = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/) ?? [];
  const viewBox = rootAttributes.match(/viewBox="([^"]+)"/)?.[1];

  if (!viewBox) throw new Error(`Icon "${fileName}": the root <svg> needs a viewBox`);
  if (/ style="/.test(inner)) throw new Error(`Icon "${fileName}": inline style="" is not supported, use attributes`);

  return { name, key: toCamelCase(name), viewBox, body: formatBody(prefixIds(toJsxAttributes(inner), name)) };
};

/** Writes only when the content changed: no needless rebuilds in develop */
const writeIfChanged = (file, content) => {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return false;
  fs.writeFileSync(file, content);

  return true;
};

const icons = fs
  .readdirSync(ICONS_DIR)
  .filter((file) => file.endsWith(".svg"))
  .map(parseIcon)
  .sort((a, b) => a.name.localeCompare(b.name));

const GENERATED_NOTE = " * Generated by `npm run icons` (scripts/generate-icons.mjs) from src/images/icons/*.svg — do not edit by hand.";

const namesFile = `/**
 * Names of the icons in ICONS (src/components/ui/Icon/icons.tsx): camelCase key → icon name.
 * Use in code instead of string literals: <Icon name={ICON_NAMES.arrowLeft} />.
 * Strings in content.json keep the kebab-case values ("arrow-up-right").
${GENERATED_NOTE}
 */
export const ICON_NAMES = {
${icons.map(({ key, name }) => `  ${key}: "${name}",`).join("\n")}
} as const;
`;

const iconsFile = `import React from "react";

import { ICON_NAMES } from "@box/constants";
import type { TIconDefinition } from "@box/types";

/**
 * Icons of the design (one .svg per icon in src/images/icons).
 * Main color is \`currentColor\`: set it with CSS \`color\` on the icon or its parent.
 * Multi-color icons keep their secondary colors (e.g. dark circle behind currency signs).
${GENERATED_NOTE}
 */

export const ICONS = {
${icons
  .map(
    ({ key, viewBox, body }) => `  [ICON_NAMES.${key}]: {
    viewBox: "${viewBox}",
    body: (
      <>
${body}
      </>
    ),
  },`,
  )
  .join("\n")}
} satisfies Record<string, TIconDefinition>;
`;

const changed = [writeIfChanged(NAMES_FILE, namesFile) && "ICON_NAMES", writeIfChanged(ICONS_FILE, iconsFile) && "ICONS"].filter(Boolean);

console.log(`icons: ${icons.length} from src/images/icons${changed.length ? `, updated ${changed.join(" + ")}` : ", no changes"}`);
